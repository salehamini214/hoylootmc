
create table if not exists public.site_settings (
  id integer primary key check (id = 1),
  content jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  image_url text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.news enable row level security;

drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings"
on public.site_settings for select
to anon, authenticated
using (true);

drop policy if exists "Admin manages site settings" on public.site_settings;
create policy "Admin manages site settings"
on public.site_settings for all
to authenticated
using (auth.uid() = 'ADMIN_UUID'::uuid)
with check (auth.uid() = 'ADMIN_UUID'::uuid);

drop policy if exists "Public reads published news" on public.news;
create policy "Public reads published news"
on public.news for select
to anon, authenticated
using (published = true);

drop policy if exists "Admin manages all news" on public.news;
create policy "Admin manages all news"
on public.news for all
to authenticated
using (auth.uid() = 'ADMIN_UUID'::uuid)
with check (auth.uid() = 'ADMIN_UUID'::uuid);

